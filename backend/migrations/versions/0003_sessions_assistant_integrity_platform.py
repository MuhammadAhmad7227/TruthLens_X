def _enum(name: str) -> postgresql.ENUM:
    """A reference to an existing PostgreSQL enum type, with no ``CREATE TYPE`` attached.

    Every enum column in this revision goes through here, and the reason is a failure that only
    appears on the *second* run. ``op.create_table`` builds the table with ``checkfirst=False``, so a
    plain ``sa.Enum(..., name=...)`` column emits ``CREATE TYPE`` unconditionally. The first
    ``upgrade head`` from an empty database survives that only by accident: revision ``0001`` creates
    ``integrity_status`` and ``evidence_type`` in the same process, and SQLAlchemy's per-run memo then
    suppresses the duplicate. Run ``0003`` against a database already at ``0002`` - which is what every
    real deployment does - and there is no memo, the ``CREATE TYPE`` is emitted, and the upgrade dies
    with ``type "integrity_status" already exists``.

    So types are created explicitly in ``upgrade`` with ``checkfirst``, and every column here merely
    references one. It also makes the revision's type handling readable at a glance: the two types it
    introduces are in ``NEW_ENUM_LABELS``, and the two it borrows are visibly not.
    """
    labels = NEW_ENUM_LABELS.get(name) or BORROWED_ENUM_LABELS[name]
    return postgresql.ENUM(*labels, name=name, create_type=False)


def _data_loss_permitted() -> bool:
    """True only when the operator said so on the command line.

    ``alembic -x allow_data_loss=true downgrade base``. A flag rather than a prompt, because
    migrations run unattended in a deploy pipeline — and a flag survives in the logged command, which
    an interactive "y" does not.
    """
    from alembic import context  # noqa: PLC0415 - a revision is a snapshot, not a library

    value = context.get_x_argument(as_dictionary=True).get("allow_data_loss", "")
    return value.strip().lower() == "true"


def _populated_new_tables(bind: Connection) -> list[str]:
    """Which of this revision's tables hold at least one row.

    ``EXISTS`` rather than ``count(*)``: a downgrade check must not spend ten minutes counting an
    integrity table in order to decide whether it is empty. The names come from ``NEW_TABLES`` above,
    not from any input, so quoting them into the statement is safe — and ``inspect`` is used only to
    confirm the table is really there before asking about its rows.
    """
    present = set(inspect(bind).get_table_names())
    populated: list[str] = []
    for name in NEW_TABLES:
        if name not in present:
            continue
        statement = sa.text(f'SELECT EXISTS (SELECT 1 FROM "{name}")')
        if bool(bind.execute(statement).scalar()):
            populated.append(name)
    return populated


def _refuse_data_loss(bind: Connection) -> None:
    """Raise unless this downgrade can proceed without destroying rows."""
    if _data_loss_permitted():
        return
    populated = _populated_new_tables(bind)
    if not populated:
        return
    preview = ", ".join(populated)
    raise RuntimeError(
        f"refusing to downgrade revision 0003: {len(populated)} table(s) hold data ({preview}). "
        "Dropping them destroys authentication history, the assistant's cited answers, integrity "
        "sweep results and configuration changes — records AI-04 and EVID-07 exist to keep, and "
        "which DATABASE_DESIGN §11 forbids a downgrade from removing silently. If this is a "
        "deliberate, backed-up teardown, re-run with: "
        "alembic -x allow_data_loss=true downgrade <target>"
    )


